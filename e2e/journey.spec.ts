import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
import { PASSWORD, confirmationLink, createUser, login, logout, pngBytes, serviceClient, sha256, uniq } from "./helpers";

// The whole product journey on a local stack: signup → upload → quarantine and
// validation → admin ClamAV result → approval → controlled download → review.
test.describe.configure({ mode: "serial" });

const creatorName = uniq("e2ecreator");
const creatorEmail = `${creatorName}@example.test`;
const title = `E2E Quantower workspace ${creatorName.slice(-8)}`;
const xml = Buffer.from('<?xml version="1.0" encoding="utf-8"?>\n<Workspace name="E2E"><Panel type="Chart" symbol="ES"/></Workspace>\n');
let submissionUrl = "";
let slug = "";
let fileId = "";

test("visitor signs up and confirms the email", async ({ page }) => {
  await page.goto("/signup");
  await page.getByLabel("Username").fill(creatorName);
  await page.getByLabel("Email").fill(creatorEmail);
  await page.getByLabel("Password").fill(PASSWORD);
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText(/confirm/i);

  const link = await confirmationLink(creatorEmail);
  await page.goto(link);
  await page.waitForURL("**/dashboard");
  await expect(page.getByRole("heading", { name: "Creator dashboard" })).toBeVisible();
});

test("creator uploads files and screenshots and submits for review", async ({ page }) => {
  await login(page, creatorEmail);
  await page.goto("/dashboard/new");
  await page.getByLabel("Title").fill(title);
  await page.getByLabel("Short summary").fill("Order-flow workspace used by the end-to-end test.");
  await page.getByLabel("Platform", { exact: true }).selectOption("quantower");
  await page.getByLabel("Category").selectOption({ index: 1 });
  await page.getByLabel("Description").fill("Generated by the automated end-to-end test. Not a real template.");
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: /create|save|continue/i }).click();
  await page.waitForURL("**/dashboard/submissions/**");
  submissionUrl = page.url();

  // A renamed Windows executable is rejected by content sniffing, not by name.
  const exe = Buffer.concat([Buffer.from("MZ"), Buffer.alloc(200, 0x90)]);
  await page.getByLabel("Choose a template file").setInputFiles({ name: "evil.xml", mimeType: "text/xml", buffer: exe });
  await expect(page.getByRole("alert").filter({ hasText: "Windows executable" })).toBeVisible();

  // The rejected file stays listed with its reason until the creator removes it.
  page.on("dialog", (d) => d.accept());
  await page.getByRole("listitem").filter({ hasText: "evil.xml" }).getByRole("button", { name: "Remove" }).click();
  await expect(page.getByRole("listitem").filter({ hasText: "evil.xml" })).toHaveCount(0);

  await page.getByLabel("Choose a template file").setInputFiles({ name: "workspace.xml", mimeType: "text/xml", buffer: xml });
  await expect(page.getByText("Validated and queued for a malware scan.")).toBeVisible();

  await page.getByLabel("Choose screenshots").setInputFiles({ name: "shot.png", mimeType: "image/png", buffer: await pngBytes() });
  await expect(page.getByText("Ready", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Cover", { exact: true })).toBeVisible();

  await page.getByRole("button", { name: "Submit for review" }).click();
  await expect(page.getByText("Pending review").first()).toBeVisible();

  const db = serviceClient();
  const { data } = await db.from("templates").select("id, slug, publication_status, template_files(id, sha256, scan_status, is_current)").eq("title", title).single();
  expect(data?.publication_status).toBe("pending");
  const current = data!.template_files.filter((f) => f.is_current);
  expect(current).toHaveLength(1);
  expect(current[0].sha256).toBe(sha256(xml));
  expect(current[0].scan_status).toBe("pending");
  slug = data!.slug;
  fileId = current[0].id;
});

test("pending listings are not public and cannot be downloaded", async ({ page, request }) => {
  const res = await request.get(`/t/${slug}`);
  expect(res.status()).toBe(404);
  const reader = await createUser(uniq("e2ereader"));
  await login(page, reader.email, "/library");
  const dl = await page.request.get(`/api/download/${fileId}`, { headers: { accept: "application/json" }, maxRedirects: 0 });
  expect([403, 404]).toContain(dl.status());
});

test("admin records a ClamAV result for the downloaded bytes and approves", async ({ page }) => {
  const admin = await createUser(uniq("e2eadmin"), "admin");
  await login(page, admin.email, "/admin/queue");
  const { data: t } = await serviceClient().from("templates").select("id").eq("slug", slug).single();
  await page.goto(`/admin/submissions/${t!.id}`);

  // Approval is impossible before a scan.
  await expect(page.getByRole("button", { name: "Approve & publish" })).toBeDisabled();

  const [download] = await Promise.all([
    page.waitForEvent("download"),
    page.getByRole("link", { name: "Download quarantined file for scanning" }).click(),
  ]);
  const scanned = await readFile((await download.path())!);
  expect(sha256(scanned)).toBe(sha256(xml));

  await page.getByLabel("Engine version").fill("ClamAV 1.5.4");
  await page.getByLabel("Signature database").fill("daily 27801 (e2e)");
  await page.getByLabel("SHA-256 of the scanned file").fill(sha256(scanned));
  await page.getByRole("button", { name: "Record scan result" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Scan recorded: clean" })).toBeVisible();

  await page.reload();
  await page.getByRole("button", { name: "Approve & publish" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Approved and published." })).toBeVisible();
  const { data: after } = await serviceClient().from("templates").select("publication_status").eq("slug", slug).single();
  expect(after?.publication_status).toBe("approved");
});

test("visitors find the template, downloads require login and are counted once", async ({ page }) => {
  await logout(page);
  await page.goto(`/browse?q=${encodeURIComponent(title.split(" ").slice(-1)[0])}`);
  await page.getByRole("link", { name: new RegExp(title) }).first().click();
  await expect(page.getByRole("heading", { name: title })).toBeVisible();
  await expect(page.getByText(/ClamAV scan passed/i)).toBeVisible();
  await expect(page.getByText(/100% (virus|safe)/i)).toHaveCount(0);

  const anon = await page.request.get(`/api/download/${fileId}`, { maxRedirects: 0 });
  expect(anon.status()).toBe(303);
  expect(anon.headers().location).toContain("/login");

  const user = await createUser(uniq("e2euser"));
  await login(page, user.email, `/t/${slug}`);
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("link", { name: "Download" }).first().click()]);
  const bytes = await readFile((await download.path())!);
  expect(sha256(bytes)).toBe(sha256(xml));

  // Second download inside 24h is served but not counted again.
  const again = await page.request.get(`/api/download/${fileId}`, { maxRedirects: 0 });
  expect(again.status()).toBe(303);
  const { data } = await serviceClient().from("templates").select("download_count").eq("slug", slug).single();
  expect(data?.download_count).toBe(1);

  // Review and favorite, then see them in the library.
  await page.reload();
  await page.getByLabel("4★").check();
  await page.getByRole("textbox", { name: /^Review/ }).fill("Works as described in the e2e test.");
  await page.getByRole("button", { name: "Publish review" }).click();
  await expect(page.getByText("Works as described in the e2e test.").first()).toBeVisible();
  await page.getByRole("button", { name: "☆ Save" }).click();
  await expect(page.getByRole("button", { name: "★ Saved" })).toBeVisible();
  await page.goto("/library");
  await expect(page.getByRole("link", { name: title }).first()).toBeVisible();
});

test("replacing an approved file sends the listing back to review", async ({ page }) => {
  await login(page, creatorEmail, "/dashboard");
  await page.goto(submissionUrl);
  page.on("dialog", (d) => d.accept());
  await page.getByRole("button", { name: "Replace" }).first().click();
  // The click opens the file chooser via the hidden input.
  await page
    .getByLabel("Choose a template file")
    .setInputFiles({ name: "workspace.xml", mimeType: "text/xml", buffer: Buffer.from(xml.toString().replace("ES", "NQ")) });
  await expect(page.getByText("Validated and queued for a malware scan.")).toBeVisible();
  const { data } = await serviceClient().from("templates").select("publication_status").eq("slug", slug).single();
  expect(data?.publication_status).toBe("pending");
  const dl = await page.request.get(`/api/download/${fileId}`, { headers: { accept: "application/json" }, maxRedirects: 0 });
  expect(dl.status()).toBeGreaterThanOrEqual(400);
});
